"""
synthesize.py — compose the final answer from the retrieved evidence.

THE TRUST BOUNDARY.
  * Tables are shown to the model as the source's own HTML, layout intact (rowspan,
    colspan, <br> multi-values). The model READS values out of them; it is not asked to
    calculate. aggregate_guard enforces that distinction and says so when a question
    crosses it.
  * Provenance and data-quality warnings are computed IN CODE from the database and from
    the budget report, not generated by the model — a model that can forget to cite can
    also forget to warn.
  * If a lane returned nothing, we say so rather than letting the model improvise.

HISTORY. This used to run a text-to-SQL lane: the model wrote a SELECT over the flattened
table_cells store and copied the resulting numbers. That was replaced because the store
cannot represent the shape of these documents' tables — body rowspans and <br>
multi-values are lost before the unpivot — and because on this corpus most documents have
no structured cells at all, so the lane silently had nothing to query. The cost of the
change is aggregation, which is now explicitly refused rather than silently approximated.
"""

import logging
from typing import Any, Dict, List, Optional, Sequence

from . import (aggregate_guard, db, llm_client, prompt_budget, prose_search, router,
               table_search)

logger = logging.getLogger("rag.synthesize")

_SYSTEM = """You answer questions about OCR'd documents and tabular data.

STRICT RULES:
1. Use ONLY the EVIDENCE below. Never use outside knowledge about the domain.
2. Read values directly out of the TABLES and DOCUMENT EXCERPTS. Never invent a number. If a cell is blank or shows "-", say it is not recorded — do not substitute a nearby value.
2a. Each TABLE is rectangular: every row has exactly one cell per column, in the same order as the header row. So the Nth cell of a row always belongs to the Nth header — map them straight across, and do not try to guess at merged or missing cells.
   - A value repeated down several rows (e.g. one hole size beside four depth intervals) is a merged cell from the original page and genuinely applies to each of those rows.
   - "a<br>b" in one cell means two separate readings for that row, not one value. Report both.
2b. Do NOT calculate across rows — no averages, sums, counts, minimums or maximums — unless a NOTE below explicitly permits it. Reading a value is always allowed.
3. If the evidence does not answer the question, say so plainly.
4. Be concise and direct. Provide a short, focused answer based on the evidence. Do not write long paragraphs. Do not invent citations — they are added automatically.
5. Do not mention the retrieval process or how the evidence was obtained; just answer the question.
6. If your answer references tabular data or you are extracting information from a table, you MUST format that information as a Markdown table (using | characters) in your response.

FORMATTING (structure answers like a well-written ChatGPT response):
7. Break a substantive answer into sections with Markdown headings (## or ###) — e.g. a
   heading per sub-topic, per document, or per aspect of the question. A short, single-fact
   answer does not need a heading; do not force structure onto a one-line answer.
8. Use a bulleted or numbered Markdown list whenever the question asks for multiple items,
   steps, comparisons, or a breakdown (e.g. "list...", "what are the...", "compare...",
   "summarize the corrections and note any blanks") — one item per line, not run together
   in a paragraph.
9. Use **bold** sparingly to flag the specific value/answer inside a sentence or list item,
   the way a key term or number would be highlighted in a well-formatted written answer."""


def _quality_warnings(report: Dict[str, Any], used_tables: bool) -> List[str]:
    """
    Computed from the DB and from the budget report, never from the model.

    Rewritten from the SQL-era version, which was gated on `used_sql=True`. That gate meant
    a prose-only answer emitted NO warnings at all — so simply deleting the SQL lane would
    have silently deleted the "these values are unverified OCR" caveat from every answer in
    the system. It is now keyed on "this answer used tabular evidence", which is the
    condition it should always have been keyed on.

    Every entry the budget dropped becomes a named warning: a table omitted for space must
    never be indistinguishable from a table that does not exist.
    """
    warns: List[str] = []
    if used_tables:
        warns.append("⚠ Table values are transcribed by OCR and have not been checked by a "
                     "human. Verify any figure against the source page before relying on it.")
    for m in (report.get("malformed") or []):
        warns.append(f"⚠ The table on {m.get('filename')} p{m.get('page')} is an INCOMPLETE "
                     f"OCR read — the transcription stops mid-table, so rows are missing.")
    for d in (report.get("dropped") or []):
        why = ("it is too large for the model's context window"
               if d.get("reason") == "too_large" else
               "higher-ranked evidence used the available space")
        cap = f" ({d['caption']})" if d.get("caption") else ""
        warns.append(f"⚠ A table on {d.get('filename')} p{d.get('page')}{cap} was NOT shown "
                     f"to the model — {why}. Ask about that page directly to see it.")
    if report.get("prose_clipped"):
        warns.append(f"⚠ {report['prose_clipped']} document excerpt(s) were shortened to fit.")
    if used_tables and db.available():
        try:
            _, rows = db.run_readonly(
                "SELECT count(*) FILTER (WHERE NOT well_formed), count(*) FROM page_tables")
            bad, total = int(rows[0][0]), int(rows[0][1])
            if bad:
                warns.append(f"⚠ {bad:,} of {total:,} stored tables in the corpus are "
                             f"incomplete OCR reads and may under-report.")
        except Exception as e:
            logger.warning("[rag.synthesize] table quality check failed: %s", e)
    return warns


def _relevant_figures(prose_hits: List[Dict[str, Any]], limit: int = 4) -> List[Dict[str, Any]]:
    """Corpus figures that sit on the SAME (document, page) as the prose evidence the
    answer is built from — so an image only appears when it belongs to a page we actually
    drew on, keeping it tied to the asked context instead of pulled from anywhere in the
    corpus. Returned in prose-hit (relevance) order. Best-effort; never raises to the caller.

    The frontend fetches each image from /rag/figure-image?ref=<image_ref> and can deep-link
    the thumbnail back to its source page (filename + page)."""
    if not db.available() or not prose_hits:
        return []
    seen, pairs = set(), []
    for h in prose_hits:
        key = (h["filename"], int(h["page"]))
        if key not in seen:
            seen.add(key)
            pairs.append(key)
    files = [f for f, _ in pairs]
    pages = [p for _, p in pairs]
    try:
        with db.connect(readonly=True) as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "SELECT d.filename, f.page, f.caption, f.context, f.image_ref "
                    "FROM figures f JOIN documents d USING (doc_id) "
                    "WHERE d.status = 'ready' AND d.filename = ANY(%s) AND f.page = ANY(%s)",
                    (files, pages))
                rows = cur.fetchall()
    except Exception as e:
        logger.warning("[rag.synthesize] figure lookup failed: %s", e)
        return []
    by_key: Dict[tuple, List[Dict[str, Any]]] = {}
    for filename, page, caption, context, ref in rows:
        by_key.setdefault((filename, int(page)), []).append({
            "filename": filename, "page": int(page), "ref": ref,
            "caption": (caption or context or "").strip()[:140],
        })
    out: List[Dict[str, Any]] = []
    for key in pairs:  # emit in relevance order, strongest evidence page first
        for fig in by_key.get(key, []):
            out.append(fig)
            if len(out) >= limit:
                return out
    return out


def answer(question: str, k_prose: int = 10, doc_ids: Optional[Sequence[int]] = None
          ) -> Dict[str, Any]:
    """
    Route -> retrieve -> narrate. Returns the answer plus the evidence behind it.

    doc_ids, if given (from the chat UI's "+" document picker), scopes both lanes to
    those documents — each lane applies the filter in its own WHERE clause, with the RLS
    policies in schema.sql as defence in depth. Omit/None for corpus-wide.
    """
    lane = router.route(question)

    prose_hits = prose_search.search(question, k=k_prose, doc_ids=doc_ids) \
        if lane in ("prose", "both") else []
    # Feed the prose hits' pages into the table lane: a question phrased about context
    # rather than about a column ("what did they do about lost circulation") matches the
    # surrounding page strongly and the table's own digest weakly.
    table_hits = table_search.search(
        question, doc_ids=doc_ids,
        pages=[(h["doc_id"], h["page"]) for h in prose_hits]) \
        if lane in ("tables", "both") else []

    evidence, report = prompt_budget.assemble_evidence(
        question, _SYSTEM, table_hits, prose_hits)

    # Computed in code from what ACTUALLY reached the prompt, then injected two ways: as a
    # NOTE the model reads, and as warnings the user sees even if the model ignores it.
    agg = aggregate_guard.classify(question, report, doc_scoped=bool(doc_ids))
    if agg["prompt_note"]:
        evidence = f"{evidence}\n\n{agg['prompt_note']}"

    warnings = _quality_warnings(report, used_tables=bool(report.get("included")))
    warnings += agg["warnings"]

    try:
        text = llm_client.complete(
            f"QUESTION: {question}\n\nEVIDENCE:\n{evidence}",
            system=_SYSTEM, max_tokens=prompt_budget.OUTPUT_RESERVE, temperature=0.0).strip()
    except llm_client.ContextOverflow as e:
        # The budget guard is supposed to make this impossible. Never let it degrade
        # silently to the local model — that answers worse while still looking like Qwen3.
        logger.error("[rag.synthesize] prompt overflow — budget guard failed: %s", e)
        text = ("The evidence for this question did not fit the model's context window, so "
                "no answer was generated. This is a bug in the evidence budget, not a limit "
                "of the documents — please report it.")
        warnings.append(f"⚠ Evidence exceeded the model's context window "
                        f"({report.get('input_tokens')} of {report.get('limit')} tokens). "
                        f"No answer was produced.")
    except Exception as e:
        logger.warning("[rag.synthesize] narration failed: %s", e)
        text = "I couldn't compose an answer, but the retrieved evidence is included below."

    # Citations span both lanes. Previously only prose hits produced them, so a table-only
    # answer was uncited — and tables are exactly the evidence a reader most wants to check.
    citations = [{"filename": h["filename"], "page": h["page"],
                  "score": round(float(h.get("score") or 0.0), 3)} for h in prose_hits]
    citations += [{"filename": t["filename"], "page": t["page"], "score": 1.0}
                  for t in (report.get("included") or [])]

    return {
        "question": question,
        "answer": text,
        "lane": lane,
        "figures": _relevant_figures(prose_hits),
        # Retained for one release so an older frontend build cannot KeyError on them.
        # Nothing reads these now that the SQL lane is gone.
        "sql": None,
        "sql_error": None,
        "columns": [],
        "rows": [],
        "tables_used": report.get("included") or [],
        "tables_dropped": report.get("dropped") or [],
        "input_tokens": report.get("input_tokens"),
        "citations": citations,
        "warnings": warnings,
        "backend": llm_client.last_backend(),
    }
